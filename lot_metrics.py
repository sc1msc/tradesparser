import re

# Признаки повреждений в тексте лота (title). Используются так:
#   - build_lot_selections.py исключает такие лоты из топа по выгодности
#     (огромный дисконт у них объясняется состоянием, а не выгодой -
#     Auto.ru оценивает исправный авто того же года/модели);
#   - мини-апп ставит на карточке значок "возможно, повреждён" и пишет на
#     экране лота, что нашлось; ТОТАЛЬНЫЕ признаки (TOTAL_DAMAGE_RULES) ещё
#     и прячут лот галочкой "Скрыть битые" (по умолчанию включена).
# "Битый" для галочки - тотальные повреждения, как в проверке фото
# (check_damage_photos.py): сгорела, на запчасти, разобрана, затоплена.
# После ДТП и "битая" - часто ремонтопригодно: только значок.
# Убраны 06.10.2026: "не на ходу", "неисправн", "требует ремонта" - это не
# повреждения кузова (разряжен аккумулятор, неисправна противотуманка), и
# просто "БИТ" - совпадал с "арБИТражный управляющий".
TOTAL_DAMAGE_RULES = [
    ("годные остатки", r"ГОДНЫЕ\s+ОСТА[ТН]КИ"),
    ("разукомплектован", r"РАЗУКОМП?ЛЕКТ"),  # и с опечаткой "разукомлектован"
    ("на утилизацию", r"УТИЛИЗАЦ"),
    ("после пожара", r"ПОСЛЕ\s+ПОЖАРА|ПОСЛЕ\s+ВОЗГОРАНИЯ"),
    ("сгоревший", r"СГОРЕВШ|ОБГОРЕВШ|ОБГОРЕЛ"),
    ("затоплен", r"ЗАТОПЛЕН"),
    ("конструктивная гибель", r"КОНСТРУКТИВН\w*\s+ГИБЕЛ"),
    ("нет двигателя", r"ДВИГАТЕЛ\w*\s+(ДЕМОНТИРОВАН|СНЯТ|ОТСУТСТВУ)|БЕЗ\s+ДВИГАТЕЛЯ|ОТСУТСТВУЕТ\s+ДВИГАТЕЛЬ"),
]
DAMAGE_RULES = TOTAL_DAMAGE_RULES + [
    ("битая", r"(?<![А-Я])БИТ(АЯ|ЫЙ|ОЕ|ЫЕ|УЮ|ОГО)(?![А-Я])"),
    ("после ДТП", r"ДТП"),
    ("аварийный", r"АВАРИЙН"),
]
# "участие в ДТП - нет", "в ДТП не участвовал", "без ДТП" - не повреждение
_DTP_DENIED_RE = re.compile(r"ДТП\s*[-–—:]?\s*(НЕТ|НЕ\s)|(НЕ\s+УЧАСТВ|БЕЗ)\W*(\w+\W+)?ДТП")


def _found(rules, text):
    upper = (text or "").upper().replace("Ё", "Е")
    out = []
    for label, pattern in rules:
        if not re.search(pattern, upper):
            continue
        if label == "после ДТП" and all(_DTP_DENIED_RE.search(upper[max(0, m.start() - 30):m.end() + 12])
                                         for m in re.finditer("ДТП", upper)):
            continue
        out.append(label)
    return out


def damage_keywords(text):
    """Какие признаки повреждений нашлись в тексте (подписи для показа;
    пустой список - ничего)."""
    return _found(DAMAGE_RULES, text)


def total_damage_keywords(text):
    """Только тотальные признаки: лот на запчасти - галочка "Скрыть битые" его прячет."""
    return _found(TOTAL_DAMAGE_RULES, text)


def looks_damaged(text):
    return bool(damage_keywords(text))


def gap_percent(price_current, market_low, market_high):
    """% below mkt = (market_mid - price_current) / market_mid * 100, где
    market_mid = (low + high) / 2 - середина вилки Авто.ру.

    Положительное значение - лот дешевле рынка, отрицательное - дороже.
    None, если цена или вилка не заданы, или market_mid <= 0 (защита от
    деления на ноль/мусора) - "нет оценки", а не ноль."""
    if price_current is None or market_low is None or market_high is None:
        return None
    market_mid = (market_low + market_high) / 2
    if market_mid <= 0:
        return None
    return (market_mid - price_current) / market_mid * 100


# ---------- правдоподобие пробега ----------

# Пробег больше этого - почти наверняка ошибка источника, а не реальная
# машина (лот 7147717, Renault Logan 2007: TRONK отдал показание
# 2 224 050 км). Такой пробег считаем ОТСУТСТВУЮЩИМ - оценка Авто.ру идёт
# по году выпуска, как у лотов без пробега вообще. Порог по году
# (км в год) сознательно не ставим: такси/каршеринг набирают много.
MAX_PLAUSIBLE_MILEAGE_KM = 1_000_000


def plausible_mileage(km):
    """Пробег, если он правдоподобен, иначе None (0 и отрицательные - тоже
    "нет пробега")."""
    if km is None:
        return None
    try:
        km = int(round(float(str(km).replace(",", "."))))
    except ValueError:
        return None
    return km if 0 < km <= MAX_PLAUSIBLE_MILEAGE_KM else None


# ---------- точность оценки Авто.ру ----------

# Авто.ру (getStatsPredictByCarIdentifier) вместе с вилкой цены отдаёт
# autoru.uncertainty_percent - свою оценку погрешности прогноза (на сайте
# она не показывается, только в JSON; формула не опубликована). Чем она
# выше, тем дальше наш "% below mkt" уходит от нуля: у 262 из 788 оценок
# (ревью 29.09) она 90-100%, и "выгода" там часто - от неточной оценки, а
# не от цены. Такие лоты НЕ убираем из подборок (решение пользователя),
# а помечаем - пусть читатель сам решает. Статус "ambiguous" (Авто.ру не
# определил машину по VIN однозначно) - тоже неточная оценка.
UNCERTAIN_ESTIMATE_PERCENT = 90
UNCERTAIN_NOTE = "оценка может быть неточной"


def estimate_is_uncertain(uncertainty_percent, autoru_status=None):
    if (autoru_status or "").strip() == "ambiguous":
        return True
    try:
        return float(str(uncertainty_percent).replace(",", ".")) >= UNCERTAIN_ESTIMATE_PERCENT
    except (TypeError, ValueError):
        return False


# ---------- тип лота: машина / мультилот / право требования / доля ----------

# Не всё, что продаётся в разделе "легковой транспорт", - это одна машина:
#   - право требования (ПРАВО ТРЕБОВАНИЯ передать ВАЗ 21013, к Иванову о
#     передаче ТС, исполнительный лист об истребовании) - покупатель получает
#     не машину, а иск; цена и "% ниже рынка" бессмысленны;
#   - доля (3/4 доли автомобиля) - то же;
#   - мультилот (несколько машин одним лотом: лот 7178974 - 17 Solaris за
#     6,27 млн давал "-510%") - оценка Авто.ру одной машины к цене лота
#     отношения не имеет.
# Решение пользователя (30.09.2026): права требования и доли исключаются
# отовсюду (срез, подборки, дайджест, мини-апп), мультилоты остаются
# отдельной группой без оценки и процента.
LOT_CAR = "car"
LOT_MULTILOT = "multilot"
LOT_RIGHTS = "rights"
LOT_SHARE = "share"
EXCLUDED_KINDS = {LOT_RIGHTS, LOT_SHARE}

# "Право (требование) к ..." - со скобками; "право на получение в собственность предмета лизинга",
# "право на истребование ТС у должника" - тоже иск, а не машина (лоты 7186432, 7211106, 13.10.2026).
_RIGHTS_RE = re.compile(r"ПРАВ[АО]?\s*\(?\s*ТРЕБОВАНИ|ПРАВ[АО]?\s+НА\s+(ПОЛУЧЕНИЕ\s+В\s+СОБСТВЕННОСТЬ|ИСТРЕБОВАНИ)"
                        r"|ДЕБИТОРСК|УСТУПК[АИ]\s+ПРАВ")
# "3/4 доли", "1/2 доля", "доля в праве". Не путать с "ДОЛЖНИК".
_SHARE_RE = re.compile(r"\d+\s*/\s*\d+\s*(ДОЛ[ЯИЮ]|ЧАСТ)|ДОЛ[ЯИЮ]\s+В\s+ПРАВЕ")
_VIN_RE = re.compile(r"(?<![A-Z0-9])[A-HJ-NPR-Z0-9]{17}(?![A-Z0-9])")
# Перед номером кузова/шасси/рамы/двигателя стоит метка - это та же машина, не
# вторая (у Mazda/Volvo номер кузова отличается от VIN, но тоже 17 знаков;
# номер двигателя "А151А1DC01N002357" - 17 знаков, если читать кириллицу латиницей).
_BODY_LABEL_RE = re.compile(r"(КУЗОВ|ШАССИ|РАМ[АЫ]|КАБИН|ДВИГАТЕЛ)[^A-Z0-9]{0,30}$")


# VIN в документах торгов бывает набран кириллицей-двойниками ("Z94СВ41ВВСR041448"
# - С и В русские), и латинская регулярка его не видит. Перед поиском VIN
# двойники меняем на латиницу.
VIN_CYR_LOOKALIKES = str.maketrans("АВЕКМНОРСТУХ", "ABEKMHOPCTYX")


def vin_text(text):
    """Текст для поиска VIN: верхний регистр, кириллица-двойники - латиницей."""
    return (text or "").upper().translate(VIN_CYR_LOOKALIKES)


def find_vin(text):
    """Первый VIN в тексте лота (см. lot_vins) или None."""
    vins = lot_vins(text)
    return vins[0] if vins else None


def lot_vins(text):
    """Разные VIN в тексте лота - без номеров кузова/шасси/рамы и без чисто
    цифровых 17-значных номеров (номер уголовного дела и т.п.). Кириллица-
    двойники считаются латиницей (vin_text)."""
    # VIN ищем в тексте с латиницей вместо двойников, а метку "кузов/шасси"
    # перед ним - в исходном (иначе "КУЗОВ" превратился бы в "KYZOB");
    # замена буква в букву, позиции совпадают
    upper = (text or "").upper()
    latin = upper.translate(VIN_CYR_LOOKALIKES)
    vins = []
    for m in _VIN_RE.finditer(latin):
        vin = m.group(0)
        if vin.isdigit() or _BODY_LABEL_RE.search(upper[max(0, m.start() - 40):m.start()]):
            continue
        if vin not in vins:
            vins.append(vin)
    return vins


# ---------- госномер ----------

# Госномер РФ: буква + 3 цифры + 2 буквы + 2-3 цифры региона. Буквы - только
# те 12, что совпадают по начертанию с латиницей (ГОСТ Р 50577-93), и в
# документах торгов их набирают и латиницей: "X707HX197" (лот 7216904),
# "X707ОЕ197" - первая X латинская (7216905). До 11.10.2026 парсер искал
# только кириллицу и только между границами слова (\b), поэтому терял и
# номер, склеенный со следующим полем ("У466НХ797Идентификационный номер"):
# 45 лотов на 11.10.2026 с номером в тексте и пустым plate. Граница справа - "дальше
# не латиница и не цифра" (кириллица можно): так номер не находится внутри
# VIN. "RUS" после региона пропускаем.
PLATE_LETTERS = "АВЕКМНОРСТУХABEKMHOPCTYX"
_PLATE_RE = re.compile(
    rf"(?<![0-9A-ZА-ЯЁ])([{PLATE_LETTERS}])\s?(\d{{3}})\s?([{PLATE_LETTERS}]{{2}})\s?(\d{{2,3}})"
    r"(?:\s?RUS)?(?![0-9A-Z])")
PLATE_LAT_TO_CYR = str.maketrans("ABEKMHOPCTYX", "АВЕКМНОРСТУХ")


def find_plate(text):
    """Первый госномер в тексте - кириллицей, без пробелов ("Р131КТ77"), или None."""
    m = _PLATE_RE.search((text or "").upper())
    return "".join(m.groups()).translate(PLATE_LAT_TO_CYR) if m else None


def lot_kind(text):
    """Тип лота по тексту (title + description): LOT_RIGHTS / LOT_SHARE /
    LOT_MULTILOT / LOT_CAR. Проверено на листе lots 01.10.2026: 13 прав
    требования и 1 доля находятся почти всегда по title; мультилот - два и
    больше разных VIN (лоты 7178974 - 17 VIN, 7219980 - второй VIN только в
    описании). Нумерацию "2." как признак не используем - она часто
    встречается в правилах осмотра, а не в перечне машин."""
    upper = (text or "").upper()
    if _RIGHTS_RE.search(upper):
        return LOT_RIGHTS
    if _SHARE_RE.search(upper):
        return LOT_SHARE
    if len(lot_vins(upper)) >= 2:
        return LOT_MULTILOT
    return LOT_CAR


# ---------- характеристики из текста лота (20.10.2026) ----------
# У машин без рыночной оценки (нет VIN, оценка не нашла модель) характеристик от оценки нет. Часть
# организаторов пишет их в лоте: «2.0 л, 150 л.с., АКПП», выписка из ПТС «Мощность двигателя, л.с.
# (кВт): 150 (110)», «Рабочий объем двигателя, куб. см: 1598». Берём только однозначное: если в
# тексте два разных объёма или и «АКПП», и «механика» - поле пустое (лучше пусто, чем чужое). Газ и
# электро не ищем: «ГАЗель», «электростеклоподъёмники».
_DISP_L_RE = re.compile(r"(?<![\d.,])([0-6][.,]\d{1,2})\s*(?:Л\b|Л\.|ЛИТР|L\b)")
_DISP_CC_RE = re.compile(r"(?<!\d)(\d{3,4})(?:[.,]\d)?\s*(?:СМ\s*3|СМ³|КУБ\.?\s*СМ|СМ\.?\s*КУБ|CM3|CC\b)")
_DISP_CC_AFTER_RE = re.compile(r"(?:КУБ\.?\s*СМ|СМ\.?\s*КУБ|СМ3|СМ³)\.?\s*[:\-]?\s*(\d{3,4})(?:[.,]\d)?(?!\d)")
_POWER_RE = re.compile(r"(?<![\d.,])(\d{2,3})(?:[.,]\d+)?\s*(?:Л\.?\s*С\b|Л\.?\s*С\.|ЛС\b|Л/С|HP\b)")
_POWER_AFTER_RE = re.compile(r"(?<!/)(?<!/\s)Л\.?\s*С\.?\s*(?:\(\s*КВТ\s*\))?\s*[:\-]\s*(\d{2,3})(?:[.,]\d+)?(?!\d)")
# «кВт/л.с.: 104(141)» - сначала киловатты, в скобках лошадиные силы
_POWER_KW_FIRST_RE = re.compile(r"КВТ\s*/\s*Л\.?\s*С\.?\s*[:\-]?\s*\d{2,3}(?:[.,]\d+)?\s*[(/]\s*(\d{2,3})(?:[.,]\d+)?")
# «Тип коробки передач: механическая», «Тип привода: ПЕРЕДНИЙ» - формат выписки из ПТС
_KPP = r"(?:КПП|КОРОБК\w*(?:\s+ПЕРЕДАЧ)?)\W{0,5}"
_TEXT_TRANSMISSION = [("автомат", r"АКПП|АВТОМАТИЧЕСК\w*\s+(?:КОРОБК|КПП|ТРАНСМИСС)|АТ|" + _KPP + r"АВТОМАТ"),
                      ("механика", r"МКПП|МЕХАНИЧЕСК\w*\s+(?:КОРОБК|КПП|ТРАНСМИСС)|" + _KPP + r"МЕХАН"),
                      ("вариатор", r"ВАРИАТОР|CVT"),
                      ("робот", r"РОБОТ\w*\s+(?:КОРОБК|КПП)|DSG|" + _KPP + r"РОБОТ")]
_TEXT_DRIVE = [("полный", r"ПОЛН\w*\s+ПРИВОД|4WD|AWD|4[XХ]4|ПРИВОД\w*\W{0,5}ПОЛН"),
               ("передний", r"ПЕРЕДН\w*\s+ПРИВОД|ПРИВОД\w*\W{0,5}ПЕРЕДН"),
               ("задний", r"ЗАДН\w*\s+ПРИВОД|ПРИВОД\w*\W{0,5}ЗАДН")]
_TEXT_FUEL = [("дизель", r"ДИЗЕЛ"), ("бензин", r"БЕНЗИН"), ("гибрид", r"ГИБРИД")]


def _one(values):
    values = {v for v in values if v is not None}
    return values.pop() if len(values) == 1 else None


def specs_from_text(text):
    """{engine_type, displacement (см³), power (л.с.), drive, transmission} из текста лота; чего нет
    или что противоречиво - None. Значения - как у рыночной оценки (autoru_valuation.parse_specs)."""
    t = (text or "").upper()
    disp = [round(float(m.replace(",", ".")) * 1000) for m in _DISP_L_RE.findall(t)]
    disp += [int(m) for m in _DISP_CC_RE.findall(t) + _DISP_CC_AFTER_RE.findall(t)]
    # объём из литров округляем как в объявлениях (1.6 л = 1598 см³): сравниваем по десятым литра
    disp = [d for d in disp if 600 <= d <= 7000]
    disp_l = _one(round(d / 100) for d in disp)
    power = _one(int(m) for m in _POWER_RE.findall(t) + _POWER_AFTER_RE.findall(t) + _POWER_KW_FIRST_RE.findall(t)
                 if 40 <= int(m) <= 700)

    def pick(rules):
        return _one(name for name, rx in rules if re.search(rx, t))
    return {
        "engine_type": pick(_TEXT_FUEL),
        "displacement": next(d for d in disp if round(d / 100) == disp_l) if disp_l else None,
        "power": power,
        "drive": pick(_TEXT_DRIVE),
        "transmission": pick(_TEXT_TRANSMISSION),
    }
